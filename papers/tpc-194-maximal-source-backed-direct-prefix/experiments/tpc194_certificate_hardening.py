class ContractError(RuntimeError):
    """Raised when a certificate violates the pinned semantic contract."""


def require(condition: bool, code: str) -> None:
    if not condition:
        raise ContractError(code)


def canonical(value: object) -> str:
    return json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def raw_sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def canonical_text_hash(path: Path) -> str:
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n").replace("\r", "\n")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _reject_duplicate_pairs(pairs: list[tuple[str, object]]) -> dict:
    result: dict[str, object] = {}
    for key, value in pairs:
        require(key not in result, f"DUPLICATE_JSON_KEY:{key}")
        result[key] = value
    return result


def load_json(path: Path, *, canonical_bytes: bool = False) -> dict:
    raw = path.read_bytes()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise ContractError(f"NON_UTF8_JSON:{path}") from exc
    try:
        value = json.loads(text, object_pairs_hook=_reject_duplicate_pairs)
    except (json.JSONDecodeError, ContractError) as exc:
        raise ContractError(f"INVALID_JSON:{path}:{exc}") from exc
    require(type(value) is dict, f"JSON_ROOT_NOT_OBJECT:{path}")
    if canonical_bytes:
        require(
            raw == canonical(value).encode("utf-8"),
            f"NONCANONICAL_RAW_JSON:{path}",
        )
    return value


def strict_equal(actual: object, expected: object, path: str) -> None:
    require(type(actual) is type(expected), f"TYPE_MISMATCH:{path}")
    if type(expected) is dict:
        expected_dict = expected
        actual_dict = actual
        require(
            set(actual_dict) == set(expected_dict),
            f"KEY_SET_MISMATCH:{path}",
        )
        for key in expected_dict:
            strict_equal(actual_dict[key], expected_dict[key], f"{path}.{key}")
        return
    if type(expected) is list:
        expected_list = expected
        actual_list = actual
        require(
            len(actual_list) == len(expected_list),
            f"ARRAY_LENGTH_MISMATCH:{path}",
        )
        for index, (left, right) in enumerate(zip(actual_list, expected_list)):
            strict_equal(left, right, f"{path}[{index}]")
        return
    require(actual == expected, f"VALUE_MISMATCH:{path}")


