def verify_active_artifacts() -> dict:
    results: dict[str, dict] = {}
    for paper in (194, 203):
        bundle = _artifact_bundle(paper)
        for path in bundle.values():
            require(path.is_file(), f"MISSING_ACTIVE_ARTIFACT:{path}")
        payload = load_json(bundle["payload"], canonical_bytes=True)
        audit = load_json(bundle["audit"], canonical_bytes=True)
        payload_schema = load_json(bundle["payload_schema"], canonical_bytes=True)
        audit_schema = load_json(bundle["audit_schema"], canonical_bytes=True)
        payload_schema_id = (
            f"tpc-{paper}-"
            + (
                "maximal-source-backed-direct-prefix"
                if paper == 194
                else "mvp10-direct-pointwise-route-decision"
            )
            + "-v2.schema.json"
        )
        audit_schema_id = payload_schema_id.replace("-v2.schema.json", "-audit-v2.schema.json")
        strict_equal(
            normalize_schema_order(payload_schema),
            normalize_schema_order(exact_schema(payload, payload_schema_id)),
            f"artifact.{paper}.payload_schema",
        )
        strict_equal(
            normalize_schema_order(audit_schema),
            normalize_schema_order(exact_schema(audit, audit_schema_id)),
            f"artifact.{paper}.audit_schema",
        )
        require(
            schema_accepts(payload_schema, payload),
            f"ACTIVE_PAYLOAD_SCHEMA_REJECTED:{paper}",
        )
        require(
            schema_accepts(audit_schema, audit),
            f"ACTIVE_AUDIT_SCHEMA_REJECTED:{paper}",
        )
        if paper == 194:
            semantic = validate_tpc194_payload(payload, REPO, True)
            registry = tpc194_semantic_mutation_registry(payload)
        else:
            semantic = validate_tpc203_payload(payload, REPO, True)
            tpc194 = load_json(REPO / TPC194_REL, canonical_bytes=True)
            registry = tpc203_semantic_mutation_registry(tpc194, payload)
        strict_equal(
            audit["finite_check_result"],
            semantic,
            f"artifact.{paper}.finite_check_result",
        )
        strict_equal(
            audit["semantic_contract_result"],
            semantic,
            f"artifact.{paper}.semantic_contract_result",
        )
        strict_equal(
            audit["semantic_mutation_registry"],
            registry,
            f"artifact.{paper}.semantic_mutation_registry",
        )
        require(
            all(row["semantic_contract_rejected"] for row in registry),
            f"SEMANTIC_MUTATION_ACCEPTED:{paper}",
        )
        require(
            all(
                row.get(
                    "regenerated_schema_accepts",
                    row.get("regenerated_schemas_accept"),
                )
                for row in registry
            ),
            f"REGENERATION_FIXTURE_INVALID:{paper}",
        )
        require(
            all(row["rejected"] for row in audit["mutation_registry"]),
            f"BASE_MUTATION_ACCEPTED:{paper}",
        )
        require(
            all(value is True for value in audit["checks"].values()),
            f"AUDIT_CHECK_FALSE:{paper}",
        )
        require(audit["all_checks_pass"] is True, f"AUDIT_NOT_ALL_PASS:{paper}")
        results[str(paper)] = {
            "semantic_mutations_rejected": len(registry),
            **semantic,
        }
    return results


