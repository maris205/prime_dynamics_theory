def exact_schema(value: object, schema_id: str | None = None) -> dict:
    if type(value) is bool:
        result = {"type": "boolean", "const": value}
    elif type(value) is int:
        result = {"type": "integer", "const": value}
    elif type(value) is float:
        result = {"type": "number", "const": value}
    elif type(value) is str:
        result = {"type": "string", "const": value}
    elif value is None:
        result = {"type": "null", "const": None}
    elif type(value) is list:
        result = {
            "type": "array",
            "minItems": len(value),
            "maxItems": len(value),
            "prefixItems": [exact_schema(item) for item in value],
            "items": False,
        }
    elif type(value) is dict:
        result = {
            "type": "object",
            "additionalProperties": False,
            "required": list(value),
            "properties": {key: exact_schema(item) for key, item in value.items()},
        }
    else:
        raise TypeError(type(value))
    if schema_id is not None:
        result = {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$id": schema_id,
            **result,
        }
    return result


def schema_accepts(schema: dict, value: object) -> bool:
    if "const" in schema:
        return type(value) is type(schema["const"]) and value == schema["const"]
    if schema.get("type") == "object":
        if type(value) is not dict:
            return False
        required = schema["required"]
        return (
            set(value) == set(required)
            and schema.get("additionalProperties") is False
            and all(
                schema_accepts(schema["properties"][key], value[key])
                for key in required
            )
        )
    if schema.get("type") == "array":
        if type(value) is not list or len(value) != schema["minItems"]:
            return False
        return all(
            schema_accepts(item_schema, item)
            for item_schema, item in zip(schema["prefixItems"], value)
        )
    return False


def normalize_schema_order(value: object) -> object:
    """Normalize only JSON-Schema order-insensitive required-name arrays."""
    if type(value) is dict:
        result = {
            key: normalize_schema_order(item) for key, item in value.items()
        }
        if "required" in result:
            result["required"] = sorted(result["required"])
        return result
    if type(value) is list:
        return [normalize_schema_order(item) for item in value]
    return value


def _semantic_rejected(call: Callable[[], object]) -> bool:
    try:
        call()
    except ContractError:
        return True
    return False


def tpc194_semantic_mutation_registry(payload: dict) -> list[dict]:
    registry = []
    for name in TPC194_SEMANTIC_MUTATIONS:
        altered = mutate_tpc194(payload, name)
        regenerated = exact_schema(altered)
        registry.append(
            {
                "name": name,
                "regenerated_schema_accepts": schema_accepts(regenerated, altered),
                "semantic_contract_rejected": _semantic_rejected(
                    lambda altered=altered: validate_tpc194_payload(
                        altered, REPO, False
                    )
                ),
            }
        )
    return registry


def tpc203_semantic_mutation_registry(
    tpc194: dict,
    tpc203: dict,
) -> list[dict]:
    registry = []
    for name in TPC203_COORDINATED_MUTATIONS:
        altered_194, altered_203 = mutate_tpc203_pair(tpc194, tpc203, name)
        regenerated_accepts = schema_accepts(
            exact_schema(altered_194), altered_194
        ) and schema_accepts(exact_schema(altered_203), altered_203)
        registry.append(
            {
                "name": name,
                "regenerated_schemas_accept": regenerated_accepts,
                "semantic_contract_rejected": _semantic_rejected(
                    lambda altered_194=altered_194, altered_203=altered_203: (
                        validate_tpc194_payload(altered_194, REPO, False),
                        _validate_tpc203_with_in_memory_194(
                            altered_203, altered_194
                        ),
                    )
                ),
            }
        )
    return registry


