def build_manifest() -> dict:
    for relative in ACTIVE_ARTIFACTS:
        require((REPO / relative).is_file(), f"MANIFEST_ARTIFACT_MISSING:{relative}")
    return {
        "schema": "tpc194-certificate-hardening-manifest-v1",
        "mode": "MANUALLY_REFRESHED_NOT_BATCH_GENERATED",
        "artifacts": [
            {"path": relative, "raw_sha256": raw_sha256(REPO / relative)}
            for relative in ACTIVE_ARTIFACTS
        ],
        "semantic_contract": manifest_semantic_summary(),
    }


def verify_manifest() -> dict:
    require(MANIFEST.is_file(), "HARDENING_MANIFEST_MISSING")
    manifest = load_json(MANIFEST, canonical_bytes=True)
    require(
        set(manifest) == {"schema", "mode", "artifacts", "semantic_contract"},
        "MANIFEST_KEY_SET",
    )
    require(
        manifest["schema"] == "tpc194-certificate-hardening-manifest-v1",
        "MANIFEST_SCHEMA",
    )
    require(
        manifest["mode"] == "MANUALLY_REFRESHED_NOT_BATCH_GENERATED",
        "MANIFEST_MODE",
    )
    strict_equal(
        manifest["semantic_contract"],
        manifest_semantic_summary(),
        "manifest.semantic_contract",
    )
    require(
        [row["path"] for row in manifest["artifacts"]] == ACTIVE_ARTIFACTS,
        "MANIFEST_ARTIFACT_ALLOWLIST",
    )
    for row in manifest["artifacts"]:
        require(
            set(row) == {"path", "raw_sha256"},
            f"MANIFEST_ARTIFACT_KEY_SET:{row.get('path')}",
        )
        path = REPO / row["path"]
        require(path.is_file(), f"MANIFEST_ARTIFACT_MISSING:{row['path']}")
        require(
            raw_sha256(path) == row["raw_sha256"],
            f"MANIFEST_HASH_MISMATCH:{row['path']}",
        )
    return {
        "artifacts_pinned": len(manifest["artifacts"]),
        "trust_mode": manifest["semantic_contract"]["manifest_trust"],
    }


def main() -> None:
    if not __debug__:
        raise RuntimeError(
            "optimized Python disables assertions in imported batch code; "
            "certificate validation fails closed"
        )
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true")
    group.add_argument("--refresh-manifest", action="store_true")
    args = parser.parse_args()

    artifact_result = verify_active_artifacts()
    if args.refresh_manifest:
        MANIFEST.write_text(canonical(build_manifest()), encoding="utf-8", newline="\n")
    manifest_result = verify_manifest()
    print(
        json.dumps(
            {
                "certificate_hardening": True,
                "artifacts": artifact_result,
                "manifest": manifest_result,
                "refreshed": args.refresh_manifest,
            },
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
