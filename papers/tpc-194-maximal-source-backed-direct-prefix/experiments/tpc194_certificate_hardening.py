def _verify_source_locks(
    payload: dict,
    bindings: dict[str, str],
    repo: Path,
    verify_files: bool,
    path: str,
) -> dict[str, dict]:
    locks = payload["source_locks"]
    require(type(locks) is list, f"TYPE_MISMATCH:{path}")
    require(
        [row.get("source_id") for row in locks] == list(bindings),
        f"SOURCE_LOCK_ORDER_OR_ID_MISMATCH:{path}",
    )
    result: dict[str, dict] = {}
    for index, (source_id, expected_path) in enumerate(bindings.items()):
        row = locks[index]
        strict_equal(
            set(row),
            {
                "source_id",
                "path",
                "canonical_utf8_lf_sha256",
                "hash_semantics",
            },
            f"{path}[{index}].keys",
        )
        require(row["source_id"] == source_id, f"SOURCE_ID_MISMATCH:{source_id}")
        require(row["path"] == expected_path, f"SOURCE_PATH_REBIND:{source_id}")
        require(
            row["hash_semantics"] == "INTEGRITY_ONLY",
            f"HASH_PROMOTED_TO_THEOREM:{source_id}",
        )
        require(
            type(row["canonical_utf8_lf_sha256"]) is str
            and len(row["canonical_utf8_lf_sha256"]) == 64,
            f"INVALID_SOURCE_HASH:{source_id}",
        )
        if verify_files:
            source_path = repo / expected_path
            require(source_path.is_file(), f"MISSING_SOURCE_FILE:{source_id}")
            require(
                canonical_text_hash(source_path)
                == row["canonical_utf8_lf_sha256"],
                f"SOURCE_HASH_MISMATCH:{source_id}",
            )
        result[source_id] = row
    return result


