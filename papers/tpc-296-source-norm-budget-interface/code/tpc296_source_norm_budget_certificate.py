#!/usr/bin/env python3
"""Least-norm source cost and profile-ray audit for the TPC-295 image.

TPC-295 proved that the unrestricted finite correlation map is onto.  This
release measures the cost of the explicit least-norm preimage and compares
the weighted sign targets with the one-dimensional ray generated by the
frozen source vector.  The cost/profile atlas is high-precision numerical
evidence; the source-energy inequalities are exact linear algebra.
"""

