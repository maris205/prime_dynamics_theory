def normalize_lf(text: str) -> str:
    return text.replace("\r\n", "\n").replace("\r", "\n")


def canonical_json(value: Any) -> str:
    return json.dumps(
        value, ensure_ascii=False, indent=2, sort_keys=True
    ) + "\n"


def compact_json_bytes(value: Any) -> bytes:
    return json.dumps(
        value, ensure_ascii=False, sort_keys=True, separators=(",", ":")
    ).encode("utf-8")


def sha256_bytes(value: bytes) -> str:
    return hashlib.sha256(value).hexdigest()


def canonical_source_bytes(path: Path) -> bytes:
    text = normalize_lf(path.read_text(encoding="utf-8"))
    if path.suffix == ".json":
        return canonical_json(json.loads(text)).encode("utf-8")
    return text.encode("utf-8")


def canonical_source_hash(path: Path) -> str:
    return sha256_bytes(canonical_source_bytes(path))


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for line_number, line in enumerate(
        normalize_lf(path.read_text(encoding="utf-8")).splitlines(), 1
    ):
        if line.strip():
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number}: {exc}") from exc
    return rows


def q(
    real_numerator: int,
    real_denominator: int = 1,
    imag_numerator: int = 0,
    imag_denominator: int = 1,
) -> dict[str, dict[str, int]]:
    real = Fraction(real_numerator, real_denominator)
    imag = Fraction(imag_numerator, imag_denominator)
    return {
        "real": {
            "numerator": real.numerator,
            "denominator": real.denominator,
        },
        "imag": {
            "numerator": imag.numerator,
            "denominator": imag.denominator,
        },
    }


def parse_scalar(
    value: Any, label: str = "exact scalar"
) -> tuple[Fraction, Fraction]:
    if not isinstance(value, dict) or set(value) != {"real", "imag"}:
        raise ValueError(f"{label}: exact Gaussian-rational object required")
    result: list[Fraction] = []
    for coordinate in ("real", "imag"):
        part = value[coordinate]
        if not isinstance(part, dict) or set(part) != {
            "numerator",
            "denominator",
        }:
            raise ValueError(f"{label}.{coordinate}: exact fraction required")
        numerator = part["numerator"]
        denominator = part["denominator"]
        if (
            isinstance(numerator, bool)
            or isinstance(denominator, bool)
            or not isinstance(numerator, int)
            or not isinstance(denominator, int)
            or denominator <= 0
        ):
            raise ValueError(
                f"{label}.{coordinate}: integer numerator and positive "
                "integer denominator required"
            )
        if math.gcd(abs(numerator), denominator) != 1:
            raise ValueError(f"{label}.{coordinate}: fraction is not reduced")
        result.append(Fraction(numerator, denominator))
    return result[0], result[1]


def scalar_record(value: tuple[Fraction, Fraction]) -> dict[str, Any]:
    return q(
        value[0].numerator,
        value[0].denominator,
        value[1].numerator,
        value[1].denominator,
    )


def scalar_add(
    left: tuple[Fraction, Fraction],
    right: tuple[Fraction, Fraction],
) -> tuple[Fraction, Fraction]:
    return left[0] + right[0], left[1] + right[1]


def scalar_mul(
    left: tuple[Fraction, Fraction],
    right: tuple[Fraction, Fraction],
) -> tuple[Fraction, Fraction]:
    return (
        left[0] * right[0] - left[1] * right[1],
        left[0] * right[1] + left[1] * right[0],
    )


def require_keys(
    value: Any,
    required: Iterable[str],
    label: str,
    *,
    exact: bool = False,
) -> dict[str, Any]:
    if not isinstance(value, dict):
        raise ValueError(f"{label}: object required")
    required_set = set(required)
    missing = required_set - set(value)
    if missing:
        raise ValueError(f"{label}: missing keys {sorted(missing)}")
    if exact and set(value) != required_set:
        raise ValueError(
            f"{label}: unexpected keys {sorted(set(value) - required_set)}"
        )
    return value


def require_nonempty_string(value: Any, label: str) -> str:
    if not isinstance(value, str) or not value:
        raise ValueError(f"{label}: nonempty string required")
    return value


