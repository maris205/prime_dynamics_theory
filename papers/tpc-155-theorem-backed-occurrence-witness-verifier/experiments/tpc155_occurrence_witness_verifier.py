def exact_scalar_schema() -> dict[str, Any]:
    fraction = {
        "type": "object",
        "additionalProperties": False,
        "required": ["denominator", "numerator"],
        "properties": {
            "denominator": {"type": "integer", "minimum": 1},
            "numerator": {"type": "integer"},
        },
    }
    return {
        "type": "object",
        "additionalProperties": False,
        "required": ["imag", "real"],
        "properties": {"imag": fraction, "real": fraction},
    }


