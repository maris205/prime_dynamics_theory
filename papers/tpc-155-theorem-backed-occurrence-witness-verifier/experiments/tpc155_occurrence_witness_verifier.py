def validate_production_status(value: dict[str, Any]) -> None:
    if (
        value["schema"]
        != "tpc155-production-occurrence-witness-status-v1"
        or value["status"] != "PASS"
        or value["hash_mode"] != HASH_MODE
        or value["production_witness_present"] is not False
        or value["production_witness_path"] is not None
        or value["production_cover_path"] is not None
        or value["production_reconnection_path"] is not None
        or value["production_registry_path"] is not None
        or value["current_production_actual_witness_status"]
        != "NOT_TESTABLE"
        or set(value["actual_exports"]) != set(ACTUAL_NT_KEYS)
        or set(value["actual_exports"].values()) != {"NOT_TESTABLE"}
        or any(value["claim_boundary"].values())
    ):
        raise ValueError("production NOT_TESTABLE boundary was promoted")


def refresh_occurrence_total(
    witness: dict[str, Any], occurrence_id: str
) -> None:
    cut_index = {
        cut["source_cut_path_id"]: cut for cut in witness["cuts"]
    }
    occurrence = next(
        item
        for item in witness["occurrences"]
        if item["occurrence_id"] == occurrence_id
    )
    chain = occurrence["multiplier_chain"]
    chain["lift_edge_weight"] = occurrence["lift_edge_weight"]
    chain["cut_multiplier"] = cut_index[
        occurrence["source_cut_path_id"]
    ]["cut_multiplier"]
    total = parse_scalar(chain["cut_multiplier"])
    total = scalar_mul(total, parse_scalar(chain["lift_edge_weight"]))
    for factor in chain["downstream_factors"]:
        total = scalar_mul(total, parse_scalar(factor["scalar"]))
    chain["recorded_total"] = scalar_record(total)


