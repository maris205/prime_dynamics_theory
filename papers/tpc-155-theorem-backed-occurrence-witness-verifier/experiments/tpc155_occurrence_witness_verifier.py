def verify_external(args: argparse.Namespace) -> None:
    paths = (
        args.witness,
        args.cover,
        args.reconnection,
        args.registry,
    )
    if any(path is None for path in paths):
        raise SystemExit(
            "--witness, --cover, --reconnection and --registry are "
            "required together"
        )
    result = validate_witness(
        load_json(Path(args.witness)),
        load_json(Path(args.cover)),
        load_json(Path(args.reconnection)),
        load_json(Path(args.registry)),
        production=args.production,
    )
    print("TPC-155 EXTERNAL VERIFY PASS")
    print(json.dumps(result, sort_keys=True))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--witness")
    parser.add_argument("--cover")
    parser.add_argument("--reconnection")
    parser.add_argument("--registry")
    parser.add_argument("--production", action="store_true")
    args = parser.parse_args()

    external = any(
        value is not None
        for value in (
            args.witness,
            args.cover,
            args.reconnection,
            args.registry,
        )
    )
    if external:
        if args.check:
            raise SystemExit("--check cannot be combined with external paths")
        verify_external(args)
        return
    if args.production:
        raise SystemExit("--production requires an external four-file bundle")

    outputs = build()
    if args.check:
        for path, expected in outputs.items():
            if not path.is_file() or path.read_bytes() != expected:
                raise SystemExit(f"DRIFT: {path}")
        print("TPC-155 CHECK PASS")
    else:
        for path, value in outputs.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(value)
        print("TPC-155 WRITE PASS")
    audit = json.loads(outputs[AUDIT_PATH])
    print(
        json.dumps(
            {
                "synthetic_status": audit["synthetic_fixture"]["status"],
                "synthetic_cuts": audit["synthetic_fixture"]["cut_count"],
                "synthetic_occurrences": audit["synthetic_fixture"][
                    "occurrence_count"
                ],
                "production_actual_witness": audit["production"][
                    "current_production_actual_witness_status"
                ],
                "first_missing": audit["production"]["first_missing"][
                    "node_id"
                ],
            },
            sort_keys=True,
        )
    )


if __name__ == "__main__":
    main()
