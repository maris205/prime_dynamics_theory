def artifact_record(path: Path, value: Any) -> dict[str, Any]:
    payload = canonical_json(value).encode("utf-8")
    return {
        "path": path.relative_to(PAPER).as_posix(),
        "canonical_sha256": sha256_bytes(payload),
        "bytes": len(payload),
    }


