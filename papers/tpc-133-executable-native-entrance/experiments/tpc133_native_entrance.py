#!/usr/bin/env python3
"""Deterministic support-envelope archive generator for TPC-133.

The generator never tries to decide the exact zero set of the smooth
weight.  It enumerates every native tuple in a certified compact support
envelope and stores the coefficient as a symbolic expression tree.

Default mode writes the certificate and JSONL sample.  ``--check`` is
strictly read-only and compares the regenerated bytes with the committed
artifacts.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from fractions import Fraction
from pathlib import Path
from typing import Any


HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
DEFAULT_MANIFEST = PAPER / "samples" / "tpc133_packet_manifest.json"
DEFAULT_ATOMS = PAPER / "samples" / "tpc133_native_atoms.jsonl"
DEFAULT_CERTIFICATE = HERE / "tpc133_native_entrance_certificate.json"


def canonical_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def pretty_json(value: Any) -> str:
    return json.dumps(value, sort_keys=True, indent=2, ensure_ascii=False) + "\n"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def ceil_div(a: int, b: int) -> int:
    if b <= 0:
        raise ValueError("ceil_div requires a positive denominator")
    return -(-a // b)


def floor_rational_power(x: int, exponent: Fraction) -> int:
    """Return floor(x**exponent) using integer arithmetic only."""
    if x < 0 or exponent < 0:
        raise ValueError("nonnegative x and exponent required")
    if x in (0, 1) or exponent == 0:
        return 1 if exponent == 0 else x
    p, q = exponent.numerator, exponent.denominator
    target = pow(x, p)
    lo, hi = 0, 1
    while pow(hi, q) <= target:
        hi *= 2
    while lo + 1 < hi:
        mid = (lo + hi) // 2
        if pow(mid, q) <= target:
            lo = mid
        else:
            hi = mid
    return lo


def mobius(n: int) -> int:
    if n < 1:
        raise ValueError("Mobius is used only on positive integers")
    remaining = n
    prime = 2
    parity = 0
    while prime * prime <= remaining:
        if remaining % prime == 0:
            remaining //= prime
            parity += 1
            if remaining % prime == 0:
                return 0
            while remaining % prime == 0:
                remaining //= prime
        prime = 3 if prime == 2 else prime + 2
    if remaining > 1:
        parity += 1
    return -1 if parity % 2 else 1


def divisors_at_most(k: int, limit: int) -> list[int]:
    return [d for d in range(1, min(k, limit) + 1) if k % d == 0]


def load_manifest(path: Path) -> dict[str, Any]:
    manifest = json.loads(path.read_text(encoding="utf-8"))
    if manifest.get("schema") != "tpc133-packet-manifest-v1":
        raise ValueError("unexpected packet manifest schema")
    required = {
        "X",
        "h0",
        "delta",
        "weight",
        "physical_normalization",
        "coefficient_language",
    }
    if not required.issubset(manifest):
        raise ValueError("packet manifest is missing required fields")
    x = manifest["X"]
    h0 = manifest["h0"]
    if not isinstance(x, int) or x < 2:
        raise ValueError("X must be an integer at least 2")
    if not isinstance(h0, int) or h0 == 0:
        raise ValueError("h0 must be a nonzero integer")
    delta = Fraction(
        manifest["delta"]["numerator"],
        manifest["delta"]["denominator"],
    )
    if not Fraction(0) < delta < Fraction(1, 2):
        raise ValueError("delta must lie strictly between 0 and 1/2")
    envelope = manifest["weight"]["support_envelope"]
    left = Fraction(
        envelope["left_numerator"],
        envelope["left_denominator"],
    )
    right = Fraction(
        envelope["right_numerator"],
        envelope["right_denominator"],
    )
    if not Fraction(0) < left < right:
        raise ValueError("support envelope must satisfy 0 < left < right")
    if not manifest["weight"].get("source_id"):
        raise ValueError("weight source id is required")
    if not manifest["weight"].get("support_proof_id"):
        raise ValueError("support proof id is required")
    if not manifest["physical_normalization"]:
        raise ValueError("one physical normalization is required")
    return manifest


def packet_parameters(manifest: dict[str, Any]) -> dict[str, Any]:
    delta = Fraction(
        manifest["delta"]["numerator"],
        manifest["delta"]["denominator"],
    )
    exponent = Fraction(1, 2) - delta
    q_value = floor_rational_power(manifest["X"], exponent)
    u_value = math.isqrt(q_value)
    return {
        "delta": delta,
        "exponent": exponent,
        "Q": q_value,
        "U": u_value,
        "V": u_value,
    }


def coefficient_ast(
    manifest: dict[str, Any],
    parameters: dict[str, Any],
    ell: int,
    k: int,
    d: int,
) -> dict[str, Any]:
    return {
        "op": "multiply",
        "args": [
            {"op": "integer", "value": -mobius(d)},
            {"op": "Lambda", "argument": ell},
            {
                "op": "r_Q",
                "Q": parameters["Q"],
                "argument": ell * k + manifest["h0"],
            },
            {
                "op": "W_eval",
                "weight_source_id": manifest["weight"]["source_id"],
                "argument": {
                    "numerator": ell * k,
                    "denominator": manifest["X"],
                },
            },
        ],
    }


def make_record(
    manifest: dict[str, Any],
    parameters: dict[str, Any],
    ell: int,
    k: int,
    d: int,
) -> dict[str, Any]:
    x = manifest["X"]
    native_id = f"X={x}|h0={manifest['h0']}|ell={ell}|k={k}|d={d}"
    scope = {
        "X": x,
        "h0": manifest["h0"],
        "Q": parameters["Q"],
        "U": parameters["U"],
        "V": parameters["V"],
        "weight_source_id": manifest["weight"]["source_id"],
        "physical_normalization": manifest["physical_normalization"],
    }
    core = {
        "schema": "tpc133-native-atom-v1",
        "native_id": native_id,
        "packet_scope": scope,
        "native_tuple": [ell, k, d],
        "coefficient_ast": coefficient_ast(manifest, parameters, ell, k, d),
        "constraint_witnesses": {
            "ell_gt_U": ell > parameters["U"],
            "k_gt_V": k > parameters["V"],
            "d_divides_k": k % d == 0,
            "d_le_V": d <= parameters["V"],
            "inside_support_envelope": True,
        },
    }
    return core | {"integrity_sha256": sha256_text(canonical_json(core))}


def canonical_record_key(record: dict[str, Any]) -> str:
    """Serialize the mathematical key, independently of its checksum."""
    return canonical_json(
        {
            "packet_scope": record["packet_scope"],
            "native_tuple": record["native_tuple"],
        }
    )


def enumerate_records(
    manifest: dict[str, Any],
    parameters: dict[str, Any],
) -> list[dict[str, Any]]:
    x = manifest["X"]
    envelope = manifest["weight"]["support_envelope"]
    left = Fraction(
        envelope["left_numerator"],
        envelope["left_denominator"],
    )
    right = Fraction(
        envelope["right_numerator"],
        envelope["right_denominator"],
    )
    minimum_product = ceil_div(left.numerator * x, left.denominator)
    maximum_product = (right.numerator * x) // right.denominator
    records: list[dict[str, Any]] = []
    ell_max = maximum_product // (parameters["V"] + 1)
    for ell in range(parameters["U"] + 1, ell_max + 1):
        k_min = max(
            parameters["V"] + 1,
            ceil_div(minimum_product, ell),
        )
        k_max = maximum_product // ell
        for k in range(k_min, k_max + 1):
            if not (minimum_product <= ell * k <= maximum_product):
                continue
            for d in divisors_at_most(k, parameters["V"]):
                records.append(make_record(manifest, parameters, ell, k, d))
    return records


def independent_count(
    manifest: dict[str, Any],
    parameters: dict[str, Any],
) -> int:
    x = manifest["X"]
    envelope = manifest["weight"]["support_envelope"]
    left = Fraction(
        envelope["left_numerator"],
        envelope["left_denominator"],
    )
    right = Fraction(
        envelope["right_numerator"],
        envelope["right_denominator"],
    )
    minimum_product = ceil_div(left.numerator * x, left.denominator)
    maximum_product = (right.numerator * x) // right.denominator
    total = 0
    for k in range(parameters["V"] + 1, maximum_product // (parameters["U"] + 1) + 1):
        ell_min = max(parameters["U"] + 1, ceil_div(minimum_product, k))
        ell_max = maximum_product // k
        if ell_min <= ell_max:
            total += (ell_max - ell_min + 1) * len(
                divisors_at_most(k, parameters["V"])
            )
    return total


def validate_records(
    records: list[dict[str, Any]],
    manifest: dict[str, Any],
    parameters: dict[str, Any],
    expected_count: int,
) -> list[str]:
    errors: list[str] = []
    tuples: set[tuple[int, int, int]] = set()
    ids: set[str] = set()
    record_keys: set[str] = set()
    envelope = manifest["weight"]["support_envelope"]
    left = Fraction(
        envelope["left_numerator"],
        envelope["left_denominator"],
    )
    right = Fraction(
        envelope["right_numerator"],
        envelope["right_denominator"],
    )
    minimum_product = ceil_div(left.numerator * manifest["X"], left.denominator)
    maximum_product = (
        right.numerator * manifest["X"]
    ) // right.denominator
    for record in records:
        if record.get("schema") != "tpc133-native-atom-v1":
            errors.append("wrong record schema")
            continue
        ell, k, d = record["native_tuple"]
        native_tuple = (ell, k, d)
        if native_tuple in tuples:
            errors.append(f"duplicate tuple {native_tuple}")
        tuples.add(native_tuple)
        if record["native_id"] in ids:
            errors.append(f"duplicate id {record['native_id']}")
        ids.add(record["native_id"])
        record_key = canonical_record_key(record)
        if record_key in record_keys:
            errors.append(f"duplicate canonical record key {record['native_id']}")
        record_keys.add(record_key)
        scope = record["packet_scope"]
        expected_scope = {
            "X": manifest["X"],
            "h0": manifest["h0"],
            "Q": parameters["Q"],
            "U": parameters["U"],
            "V": parameters["V"],
            "weight_source_id": manifest["weight"]["source_id"],
            "physical_normalization": manifest["physical_normalization"],
        }
        if scope != expected_scope:
            errors.append(f"scope mismatch for {record['native_id']}")
        expected_native_id = (
            f"X={manifest['X']}|h0={manifest['h0']}|"
            f"ell={ell}|k={k}|d={d}"
        )
        if record["native_id"] != expected_native_id:
            errors.append(f"native convenience id mismatch for {record['native_id']}")
        if not (
            ell > parameters["U"]
            and k > parameters["V"]
            and d <= parameters["V"]
            and k % d == 0
        ):
            errors.append(f"constraint mismatch for {record['native_id']}")
        if not minimum_product <= ell * k <= maximum_product:
            errors.append(f"support-envelope mismatch for {record['native_id']}")
        expected_witnesses = {
            "ell_gt_U": ell > parameters["U"],
            "k_gt_V": k > parameters["V"],
            "d_divides_k": k % d == 0,
            "d_le_V": d <= parameters["V"],
            "inside_support_envelope": minimum_product
            <= ell * k
            <= maximum_product,
        }
        if record["constraint_witnesses"] != expected_witnesses:
            errors.append(f"constraint witness mismatch for {record['native_id']}")
        expected_ast = coefficient_ast(manifest, parameters, ell, k, d)
        if record["coefficient_ast"] != expected_ast:
            errors.append(f"coefficient AST mismatch for {record['native_id']}")
        core = {key: value for key, value in record.items() if key != "integrity_sha256"}
        if record["integrity_sha256"] != sha256_text(canonical_json(core)):
            errors.append(f"integrity hash mismatch for {record['native_id']}")
    if len(records) != expected_count:
        errors.append(f"record count {len(records)} != expected {expected_count}")
    return errors


def mutation_checks(
    records: list[dict[str, Any]],
    manifest: dict[str, Any],
    parameters: dict[str, Any],
    expected_count: int,
) -> dict[str, bool]:
    if not records:
        raise ValueError("sample archive unexpectedly empty")
    first = records[0]
    duplicate = records + [first]
    deleted = records[:-1]

    wrong_shift_record = json.loads(json.dumps(first))
    wrong_shift_record["packet_scope"]["h0"] = manifest["h0"] + 2
    wrong_shift = [wrong_shift_record] + records[1:]

    wrong_norm_record = json.loads(json.dumps(first))
    wrong_norm_record["packet_scope"]["physical_normalization"] = "second_norm"
    wrong_norm = [wrong_norm_record] + records[1:]

    wrong_ast_record = json.loads(json.dumps(first))
    wrong_ast_record["coefficient_ast"]["args"][0]["value"] *= -1
    wrong_ast = [wrong_ast_record] + records[1:]

    envelope = manifest["weight"]["support_envelope"]
    maximum_product = (
        envelope["right_numerator"] * manifest["X"]
    ) // envelope["right_denominator"]
    outside_envelope_record = make_record(
        manifest,
        parameters,
        maximum_product + 1,
        first["native_tuple"][1],
        1,
    )
    outside_envelope = [outside_envelope_record] + records[1:]

    return {
        "duplicate_tuple_rejected": bool(
            validate_records(duplicate, manifest, parameters, expected_count)
        ),
        "deleted_tuple_rejected": bool(
            validate_records(deleted, manifest, parameters, expected_count)
        ),
        "wrong_h0_rejected": bool(
            validate_records(wrong_shift, manifest, parameters, expected_count)
        ),
        "second_normalization_rejected": bool(
            validate_records(wrong_norm, manifest, parameters, expected_count)
        ),
        "coefficient_ast_mutation_rejected": bool(
            validate_records(wrong_ast, manifest, parameters, expected_count)
        ),
        "outside_support_envelope_rejected": bool(
            validate_records(
                outside_envelope,
                manifest,
                parameters,
                expected_count,
            )
        ),
    }


def build_artifacts(manifest_path: Path) -> tuple[str, str, dict[str, Any]]:
    manifest = load_manifest(manifest_path)
    parameters = packet_parameters(manifest)
    records = enumerate_records(manifest, parameters)
    expected_count = independent_count(manifest, parameters)
    errors = validate_records(records, manifest, parameters, expected_count)
    mutations = mutation_checks(records, manifest, parameters, expected_count)
    atoms_text = "".join(pretty_json(record).replace("\n", "") + "\n" for record in records)
    checks = {
        "uniform_generator_sample_completed": True,
        "tuple_projection_bijective_on_sample": not errors,
        "independent_truncated_divisor_census_matches": len(records) == expected_count,
        "canonical_record_keys_unique": len(
            {canonical_record_key(record) for record in records}
        )
        == len(records),
        "native_ids_are_scope_local_convenience_labels": True,
        "integrity_hashes_are_not_record_identity": True,
        "all_records_inside_declared_support_envelope": all(
            record["constraint_witnesses"]["inside_support_envelope"]
            for record in records
        ),
        "symbolic_coefficient_ast_only": True,
        "exact_weight_zero_set_not_decided": True,
        "all_mutations_rejected": all(mutations.values()),
    }
    certificate = {
        "schema": "tpc133-native-entrance-certificate-v1",
        "status": "PASS" if all(checks.values()) else "FAIL",
        "scope": (
            "finite sample of a uniform support-envelope generator; "
            "not a numerical evaluation of W, Lambda, or r_Q"
        ),
        "packet": {
            "X": manifest["X"],
            "h0": manifest["h0"],
            "delta": str(parameters["delta"]),
            "Q": parameters["Q"],
            "U": parameters["U"],
            "V": parameters["V"],
            "weight_source_id": manifest["weight"]["source_id"],
            "support_proof_id": manifest["weight"]["support_proof_id"],
            "physical_normalization": manifest["physical_normalization"],
        },
        "archive": {
            "record_count": len(records),
            "independent_expected_count": expected_count,
            "first_native_id": records[0]["native_id"] if records else None,
            "last_native_id": records[-1]["native_id"] if records else None,
            "jsonl_sha256": sha256_text(atoms_text),
            "identity_basis": (
                "canonical (packet_scope,native_tuple) record key; "
                "native_id is a scope-local label and SHA-256 is integrity only"
            ),
        },
        "checks": checks,
        "mutation_regression": mutations,
        "validation_errors": errors,
        "claim_boundary": {
            "native_enumeration_L0": True,
            "literal_tpc15_attachment_L1_target": True,
            "complete_downstream_path_archive": False,
            "positive_fixed_h0_L2": False,
            "prime_pair_or_twin_prime_theorem": False,
        },
    }
    return atoms_text, pretty_json(certificate), certificate


def compare_bytes(path: Path, expected: str) -> None:
    if not path.exists():
        raise SystemExit(f"missing artifact: {path}")
    actual = path.read_text(encoding="utf-8")
    if actual != expected:
        raise SystemExit(f"artifact mismatch: {path}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--atoms", type=Path, default=DEFAULT_ATOMS)
    parser.add_argument("--certificate", type=Path, default=DEFAULT_CERTIFICATE)
    parser.add_argument(
        "--check",
        action="store_true",
        help="read-only deterministic comparison; never rewrites artifacts",
    )
    args = parser.parse_args()

    atoms_text, certificate_text, certificate = build_artifacts(args.manifest)
    if args.check:
        compare_bytes(args.atoms, atoms_text)
        compare_bytes(args.certificate, certificate_text)
    else:
        args.atoms.parent.mkdir(parents=True, exist_ok=True)
        args.certificate.parent.mkdir(parents=True, exist_ok=True)
        args.atoms.write_text(atoms_text, encoding="utf-8")
        args.certificate.write_text(certificate_text, encoding="utf-8")
    print(certificate_text, end="")
    if certificate["status"] != "PASS":
        raise SystemExit(1)


if __name__ == "__main__":
    main()
